GROUPS = {
    "memory": (MemoryQuery, MemoryWrite, MemoryRevision, MemoryForget, MemoryRetention, MemoryRestore, MemoryRestoreApply, MemorySource),
    "notifications": (NotificationPolicy, NotificationRule, NotificationEvent, NotificationBatch),
    "mobile": (ListenerRequest, PairRequest, PairDecision, DeviceRequest, PairClaim, SignedEnvelope, MobileEmpty, MobileHistory, MobileChat, MobilePreview, MobileReceipt),
    "speech": (SpeechTurn, SpeechBegin, SpeechFrame, SpeechSend),
    "image": (ImageRecipe, ImageRequest, ImageArtifactRequest, ImageStats, JobRequest, JobLifetime),
    "cad": (SolidRecipe, SceneObject, ScenePresentation, Recipe, BuildRequest, ArtifactRequest, PlanRequest, MeshStats, JobRequest, JobLifetime, EditableFields, ObjectEdit, ChangeSet, ChangePrompt),
}


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(value) for value in schema['anyOf'])
    kind = schema.get('type')
    if kind in ('integer', 'number'):
        return 'number'
    if kind in ('string', 'boolean', 'null'):
        return kind
    if kind == 'array':
        return f'Array<{ts_type(schema["items"])}>'
    if kind == 'object':
        if isinstance(schema.get('additionalProperties'), dict):
            return f'Record<string, {ts_type(schema["additionalProperties"])}>'
        required = schema.get('required', [])
        return '{\n' + ''.join(
            f'  {json.dumps(key)}{"" if key in required else "?"}: {ts_type(value)};\n'
            for key, value in schema.get('properties', {}).items()
        ) + '}'
    raise ValueError(f'Unsupported schema: {schema}')


def output():
    files = {}
    for group, models in GROUPS.items():
        schemas = {model.__name__: model.model_json_schema() for model in models}
        definitions = {}
        for schema in schemas.values():
            definitions.update(schema.get('$defs', {}))
        definitions.update(schemas)
        types = '// Generated by scripts/export-ui-contracts.py. Do not edit.\n'
        for name, schema in definitions.items():
            types += f'export type {name} = {ts_type(schema)};\n'
        files[ROOT / f'src/transport/generated/{group}.ts'] = types
        files[ROOT / f'src/transport/generated/{group}.schema.json'] = json.dumps(schemas, indent=2) + '\n'
    files[ROOT / 'src/transport/generated/version.ts'] = (
        '// Generated by scripts/export-ui-contracts.py. Do not edit.\n'
        f'export const UI_CONTRACT_VERSION = {UI_CONTRACT_VERSION};\n'
    )
    return files



if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in output().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Generated contract is stale: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
