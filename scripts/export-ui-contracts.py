"""Export the image request boundary from Pydantic without opening a runtime."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from services.images import ImageRecipe, ImageRequest, ImageArtifactRequest, ImageStats  # noqa: E402
from services.creative_jobs import JobRequest  # noqa: E402

MODELS = (ImageRecipe, ImageRequest, ImageArtifactRequest, ImageStats, JobRequest)


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(value) for value in schema['anyOf'])
    kind = schema.get('type')
    if kind in ('integer', 'number'):
        return 'number'
    if kind in ('string', 'boolean', 'null'):
        return kind
    if kind == 'array':
        return f'Array<{ts_type(schema["items"])}>'
    if kind == 'object':
        required = schema.get('required', [])
        return '{\n' + ''.join(
            f'  {json.dumps(key)}{"" if key in required else "?"}: {ts_type(value)};\n'
            for key, value in schema.get('properties', {}).items()
        ) + '}'
    raise ValueError(f'Unsupported schema: {schema}')


def output():
    schemas = {model.__name__: model.model_json_schema() for model in MODELS}
    types = '// Generated by scripts/export-ui-contracts.py. Do not edit.\n'
    for name, schema in schemas.items():
        types += f'export type {name} = {ts_type(schema)};\n'
    return {
        ROOT / 'src/transport/generated/image.ts': types,
        ROOT / 'src/transport/generated/image.schema.json': json.dumps(schemas, indent=2) + '\n',
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in output().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Generated contract is stale: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
